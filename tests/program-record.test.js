function hubProgram(rpc) {
  const calls = [], c = { console, esc: (s) => String(s), FFcut: () => '', document: { getElementById: () => null, createElement: () => ({}), head: { appendChild() {} } } };
  c.window = c; vm.createContext(c);
  c.FFHub = { configured: true, connected: true, client: () => ({ rpc: async (fn, args) => { calls.push([fn, JSON.parse(JSON.stringify(args))]); return rpc[fn]; } }) };
  c.FFPortal = { rerender() {} };
  vm.runInContext(read('program-record.js'), c);
  return { P: c.FFProgram, calls, flush: () => new Promise((r) => setImmediate(r)) };
}
