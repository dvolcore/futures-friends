function site(records = approved(FIX)) {
  const handlers = { click: [], change: [] }, store = {};
  const el = () => ({ hidden: true, textContent: '', innerHTML: '', value: '', focus() {}, scrollIntoView() {}, setAttribute() {}, appendChild() {} });
  const toastEl = el(), viewEl = el();
  const c = {
    console, setTimeout: () => 0, clearTimeout() {}, setInterval: () => 0, matchMedia: () => ({ matches: true }),
    localStorage: { getItem: (k) => store[k] ?? null, setItem: (k, v) => { store[k] = String(v); } },
    document: { addEventListener: (t, f) => { (handlers[t] = handlers[t] || []).push(f); }, getElementById: () => null,
      querySelector: (q) => q === '#toast' ? toastEl : q === '#view' ? viewEl : null, querySelectorAll: () => [], createElement: el, head: el(), body: el() },
    location: { hash: '' }, history: { replaceState() {} }, addEventListener() {}, scrollTo() {},
  };
  c.window = c; vm.createContext(c);
  for (const f of ['data.js', 'views.js', 'curriculum-indicators.js', 'portal.js']) vm.runInContext(f === 'curriculum-indicators.js' ? P.readPriv(f) : read(f), c, { filename: f });
  c.FF_PROGRAM = { records, sample_start: START };
  vm.runInContext(read('teach-day.js'), c, { filename: 'teach-day.js' });
  vm.runInContext(read('program-record.js'), c, { filename: 'program-record.js' });
  vm.runInContext("view='portal'", c);
  const fire = async (type, target) => { for (const h of handlers[type]) await h({ target }); };
  const node = (attrs, extra = {}) => Object.assign({ dataset: attrs, closest(sel) { const m = /^\[data-([a-z0-9-]+)\]$/.exec(sel); if (!m) return null; const key = m[1].replace(/-([a-z])/g, (_, x) => x.toUpperCase()); return key in attrs ? this : null; } }, extra);
  const html = (v) => vm.runInContext(`view=${JSON.stringify(v)}; V[${JSON.stringify(v)}]()`, c);
  const setDate = (d) => fire('change', node({}, { id: 'pDate', value: d }));
  return { c, html, fire, node, setDate, toast: () => toastEl.textContent };
}
