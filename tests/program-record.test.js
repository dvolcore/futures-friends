// E4: participation is unknown until a teacher records it, child by child or through the deliberate "Everyone here took part" action.
// what the circle card says about one child: null (not marked here, so no row), 'none' (Not recorded) or the recorded entry
// {took, by, time, v, group}. The row is drawn from the stored entry (took_part, by, at, v, via).
const NAMES = { k10: 'Mia C.', k11: 'Noah J.', k12: 'Aria Q.', k13: 'Liam X.', k14: 'Nova E.' };
const kidLog = (s, kid) => {
  const t = visible(s.html('portal')).split('Record u1-w1-d1-circle')[0];
  const m = new RegExp(`${NAMES[kid].replace('.', '\\.')} Took part Not this time Not recorded (Recorded: (took part|not this time) · ([^·]+?) · (\\d+:\\d\\d [AP]M) · version (\\d+)( · "everyone here" action)?|Not recorded)`).exec(t);
  if (!m) return null;
  return m[1] === 'Not recorded' ? 'none' : { took: m[2] === 'took part', by: m[3], time: m[4], v: +m[5], group: !!m[6] };
};
const choose = (s, kid, value, rid = 'u1-w1-d1-circle') => s.fire('change', s.node({ progKid: kid, progRec: rid }, { value }));
