// Builds room-kit-plans.js from the three to-scale floor plans in img/room-kit/*.svg (copied from the client package,
// ~/Downloads/FUTURES_FRIENDS_PROJECT/14_Client_Package/floor_plans, purple Bop, owner decisions 2026-10-07).
// Each SVG is inlined on #room-kit, so its ids are made unique per plan (all three share id="arr"), its fixed width/height are
// dropped (the viewBox scales it), and its <title> gets an id the <svg> points at with aria-labelledby.
// Run: node tools/build-room-kit-plans.mjs   (re-run after replacing an SVG)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PLANS = [['home', 'home-12x14.svg'], ['classroom', 'classroom-20x25.svg'], ['church', 'church-packaway-22x28.svg']];
const out = {};
for (const [key, file] of PLANS) {
  let s = fs.readFileSync(path.join(ROOT, 'img/room-kit', file), 'utf8').trim();
  s = s.replace(/<\?xml[^>]*>\s*/, '');
  const ids = [...s.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]);
  for (const id of ids) {
    const nu = `rk-${key}-${id}`;
    s = s.split(`id="${id}"`).join(`id="${nu}"`).split(`url(#${id})`).join(`url(#${nu})`).split(`href="#${id}"`).join(`href="#${nu}"`);
  }
  s = s.replace(/<svg([^>]*?)\swidth="\d+"\s+height="\d+"/, '<svg$1')
    .replace(/<svg /, `<svg class="rk-plan-svg" focusable="false" aria-labelledby="rk-${key}-title" `)
    .replace(/\saria-label="[^"]*"/, '')
    .replace(/<title>/, `<title id="rk-${key}-title">`)
    .replace(/>\s+</g, '><');
  out[key] = s;
}
const js = `/* GENERATED by tools/build-room-kit-plans.mjs from img/room-kit/*.svg. Do not edit by hand.
   The three to-scale Learning Zones floor plans (1 ft grid), inlined on #room-kit. */
window.FFRoomKitPlans = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(ROOT, 'room-kit-plans.js'), js);
console.log('room-kit-plans.js', js.length, 'bytes');
