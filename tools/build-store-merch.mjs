#!/usr/bin/env node
/* Writes store-merch-data.js from the owner's merchandise campaign package (store/products.json and apparel/products.json).
   The package ids are STABLE: they are the product ids in the store. Only fields the store shows are kept; price, stock and size are
   deliberately never copied (every one is null in the package). store-catalog.js adds the approved prices ($16 poster, $26 plush).
   Usage: node tools/build-store-merch.mjs [packageDir] */
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKG = process.argv[2] || join(homedir(), 'Downloads/Futures_Friends_Merchandise_Campaign_2026-10-07');
const cat = JSON.parse(readFileSync(join(PKG, 'store/products.json'), 'utf8'));
const appRaw = JSON.parse(readFileSync(join(PKG, 'apparel/products.json'), 'utf8')), app = Array.isArray(appRaw) ? appRaw : appRaw.products;
const pick = (o, keys) => Object.fromEntries(keys.filter(k => o[k] != null).map(k => [k, o[k]]));
const data = {
  source: 'Futures_Friends_Merchandise_Campaign_2026-10-07 (store/products.json, apparel/products.json); every product is a draft',
  status: cat.catalog_status,
  rugs: cat.products.filter(p => p.type === 'rug').map(p => pick(p, ['id', 'name', 'description', 'character', 'zone', 'color', 'format', 'cta'])),
  plush: cat.products.filter(p => p.type === 'plush').map(p => pick(p, ['id', 'name', 'description', 'character', 'color', 'cta'])),
  posters: cat.products.filter(p => p.type === 'poster').map(p => pick(p, ['id', 'name', 'description', 'character', 'zone', 'variant', 'cta'])),
  bundles: cat.bundles.map(b => pick(b, ['id', 'name', 'description', 'includes', 'cta'])),
  apparel: app.map(a => pick(a, ['id', 'design', 'character', 'color', 'type', 'front_copy', 'back_copy']))
};
writeFileSync(join(SITE, 'store-merch-data.js'), `/* GENERATED by tools/build-store-merch.mjs from the owner's merchandise campaign package. Do not edit by hand. */
(function (root, data) { if (typeof module === 'object' && module.exports) module.exports = data; else root.FFMerchData = data; })(typeof window !== 'undefined' ? window : globalThis, ${JSON.stringify(data, null, 1)});
`);
console.log('rugs', data.rugs.length, 'plush', data.plush.length, 'posters', data.posters.length, 'bundles', data.bundles.length, 'apparel', data.apparel.length);
