#!/usr/bin/env node
// Writes the production Futures Hub URL + PUBLIC anon key into hub-config.js, and the intake gateway URL into
// intake-config.js, from the CRM repo's deploy output (deploy/out/hub-public.json, written by deploy/push.sh).
//   node tools/set-hub-config.mjs /Volumes/FFCRM/app/deploy/out/hub-public.json     (or the JSON on stdin with "-")
// Refuses anything that is not safe to serve to every browser:
//   - the key must be a JWT whose payload says role "anon" (a service_role key or any secret is rejected),
//   - both URLs must be https on dvolcore.com.
// Only the two marked lines change; review with `git diff`, then commit.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export function anonClaims(key) {
  const parts = String(key || '').split('.');
  if (parts.length !== 3 || parts.some((p) => !/^[A-Za-z0-9_-]+$/.test(p))) throw new Error('the key is not a JWT');
  const json = (s) => JSON.parse(Buffer.from(s.replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
  const head = json(parts[0]);
  const body = json(parts[1]);
  if (head.alg !== 'HS256') throw new Error(`unexpected JWT algorithm ${head.alg}`);
  if (body.role !== 'anon') throw new Error(`refusing a key with role "${body.role}": only the PUBLIC anon key may be served to browsers`);
  if (body.iss === 'supabase-demo') throw new Error('refusing the public Supabase demo key');
  if (!body.exp || body.exp * 1000 < Date.now() + 30 * 864e5) throw new Error('the anon key expires within 30 days');
  return body;
}

export function checkUrl(u, host) {
  const url = new URL(u);
  if (url.protocol !== 'https:' || url.hostname !== host || url.pathname.replace(/\/$/, '') !== '') {
    throw new Error(`expected https://${host}, got ${u}`);
  }
  return `https://${host}`;
}

export function apply(hubSrc, intakeSrc, cfg) {
  anonClaims(cfg.hub.anonKey);
  const hubUrl = checkUrl(cfg.hub.url, 'ff-api.dvolcore.com');
  const intakeUrl = checkUrl(cfg.intake.url, 'ff-intake.dvolcore.com');
  const hubLine = /^window\.FF_HUB_PROD = \{ url: '[^']*', anonKey: '[^']*' \}; \/\/ @generated by tools\/set-hub-config\.mjs$/m;
  if (!hubLine.test(hubSrc)) throw new Error('hub-config.js: the generated FF_HUB_PROD line was not found');
  const intakeLine = /^window\.FF_INTAKE = \{ url: '[^']*', turnstileSiteKey: '([^']*)' \};$/m;
  if (!intakeLine.test(intakeSrc)) throw new Error('intake-config.js: the FF_INTAKE line was not found');
  return {
    hub: hubSrc.replace(hubLine, `window.FF_HUB_PROD = { url: '${hubUrl}', anonKey: '${cfg.hub.anonKey}' }; // @generated by tools/set-hub-config.mjs`),
    intake: intakeSrc.replace(intakeLine, (_, site) => `window.FF_INTAKE = { url: '${intakeUrl}', turnstileSiteKey: '${site}' };`),
  };
}

function main() {
  const src = process.argv[2];
  if (!src) { console.error('usage: node tools/set-hub-config.mjs <hub-public.json | ->'); process.exit(2); }
  const cfg = JSON.parse(readFileSync(src === '-' ? 0 : src, 'utf8'));
  const hubPath = join(ROOT, 'hub-config.js');
  const intakePath = join(ROOT, 'intake-config.js');
  const out = apply(readFileSync(hubPath, 'utf8'), readFileSync(intakePath, 'utf8'), cfg);
  writeFileSync(hubPath, out.hub);
  writeFileSync(intakePath, out.intake);
  console.log('hub-config.js and intake-config.js updated (public values only). Review with `git diff`, then commit.');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try { main(); } catch (e) { console.error(`refused: ${e.message}`); process.exit(1); }
}
