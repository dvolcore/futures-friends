#!/usr/bin/env node
// Writes the production website-statistics server URL + PUBLIC website id into analytics-config.js, from the CRM repo's deploy
// output (deploy/out/hub-public.json, written by deploy/push.sh; its "analytics" entry). deploy/site-config.sh runs this.
//   node tools/set-analytics-config.mjs /Volumes/FFCRM/app/deploy/out/hub-public.json     (or the JSON on stdin with "-")
// Refuses anything that is not safe and expected: the URL must be exactly https://ff-stats.dvolcore.com and the id a UUID.
// Only the one marked line changes; review with `git diff`, then commit.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const HOST = 'ff-stats.dvolcore.com';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const LINE = /^window\.FF_ANALYTICS = \{ url: '[^']*', siteId: '[^']*' \}; \/\/ @generated by tools\/set-analytics-config\.mjs$/m;

export function apply(src, cfg) {
  const a = (cfg && cfg.analytics) || {};
  const url = new URL(String(a.url || ''));
  if (url.protocol !== 'https:' || url.hostname !== HOST || url.pathname.replace(/\/$/, '') !== '' || url.search || url.port) {
    throw new Error(`expected https://${HOST}, got ${a.url}`);
  }
  if (!UUID.test(String(a.siteId || ''))) throw new Error('siteId must be a UUID (the Umami website id)');
  if (!LINE.test(src)) throw new Error('analytics-config.js: the generated FF_ANALYTICS line was not found');
  return src.replace(LINE, `window.FF_ANALYTICS = { url: 'https://${HOST}', siteId: '${String(a.siteId).toLowerCase()}' }; // @generated by tools/set-analytics-config.mjs`);
}

function main() {
  const src = process.argv[2];
  if (!src) { console.error('usage: node tools/set-analytics-config.mjs <hub-public.json | ->'); process.exit(2); }
  const cfg = JSON.parse(readFileSync(src === '-' ? 0 : src, 'utf8'));
  const path = join(ROOT, 'analytics-config.js');
  writeFileSync(path, apply(readFileSync(path, 'utf8'), cfg));
  console.log('analytics-config.js updated (public values only). Review with `git diff`, then commit.');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try { main(); } catch (e) { console.error(`refused: ${e.message}`); process.exit(1); }
}
